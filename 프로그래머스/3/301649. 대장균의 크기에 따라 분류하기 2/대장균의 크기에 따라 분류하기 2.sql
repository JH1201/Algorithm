SELECT
    ID,
    CASE 
        WHEN ROUND(PERCENT_RANK() OVER (ORDER BY SIZE_OF_COLONY DESC) * 100, 2) <= 25 THEN 'CRITICAL' 
        WHEN ROUND(PERCENT_RANK() OVER (ORDER BY SIZE_OF_COLONY DESC) * 100, 2) > 25 AND ROUND(PERCENT_RANK() OVER (ORDER BY SIZE_OF_COLONY DESC) * 100, 2) <= 50 THEN 'HIGH' 
        WHEN ROUND(PERCENT_RANK() OVER (ORDER BY SIZE_OF_COLONY DESC) * 100, 2) > 50 AND ROUND(PERCENT_RANK() OVER (ORDER BY SIZE_OF_COLONY DESC) * 100, 2) <= 75 THEN 'MEDIUM' 
        ELSE 'LOW'
    END AS COLONY_NAME
FROM ECOLI_DATA
ORDER BY ID 
